def _clean_major(m):
    return _re.sub(r'（.*?）|\(.*?\)', '', (m or '')).strip()

# 站点全部标准学科名（专业名精确等于学科名时直接匹配）
_ALL_SUBJECTS = set()
for _m in _SUPP.values():
    _ALL_SUBJECTS.update(_m.keys())

def _supp_lookup(college, subject):
    if college in _SUPP and subject in _SUPP[college]:
        return _SUPP[college][subject]
    return None

def supp_round(college, subject):
    return _SUPP_ROUND.get(college, {}).get(subject)

def _resolve_subject(major_name):
    cm = _clean_major(major_name)
    subj = _MAJOR_TO_SUBJECT.get(cm) or _MAJOR_TO_SUBJECT.get(major_name)
    if subj:
        return subj
    if cm in _ALL_SUBJECTS:
        return cm
    return None

def supp_lookup_major(college, major_name):
    """按专业名查补充学科评估等级（专硕类别名经确定性映射到标准学科名）"""
    if college not in _SUPP:
        return None
    subj = _resolve_subject(major_name)
    if not subj:
        return None
    return _SUPP[college].get(subj)

def supp_lookup_major_detail(college, major_name):
    """返回 (等级, 轮次) 或 None"""
    if college not in _SUPP:
        return None
    subj = _resolve_subject(major_name)
    if not subj:
        return None
    if subj in _SUPP[college]:
        return _SUPP[college][subj], _SUPP_ROUND[college].get(subj)
    return None